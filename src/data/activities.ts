/**
 * Curated Barcelona activities for the public preview.
 *
 * HONESTY CONTRACT (see TRUST_MODEL.md):
 *  - `verifiedLive` is `false` everywhere → the app makes ZERO "Live now"
 *    claims. Nothing here is presented as verified-live reality.
 *  - Items are labelled `curated` unless they carry a real official source
 *    (`verified` / `official_source`).
 *  - Times are relative to app load so the map is honestly populated for the
 *    Now / Tonight / Tomorrow filters, but timing never produces a live claim.
 *  - Sports are NOT invented as live: fixtures are source-linked and scheduled.
 *
 * This is the output shape of the curated ingestion adapter; networked adapters
 * will emit the same `Activity` records (see INGESTION_ARCHITECTURE.md).
 */
const MINUTE = 60 * 1000;

function at(offsetMinutes: number): string {
  return new Date(Date.now() + offsetMinutes * MINUTE).toISOString();
}

function checkedMinAgo(mins: number): string {
  return new Date(Date.now() - mins * MINUTE).toISOString();
}

function tomorrowAt(hour: number, minute = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + 1);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

